//! The project overview the assistant gets with each message: a file tree and a one-line
//! summary of every Rust file (its kind in the Cargo layout, its `mod`s, `use`s and top-level items).
//!
//! Nothing here draws. The disk is read by [`Index::scan`] on a worker thread ([`Project::poll`]);
//! the text is rendered from that index plus the text of the open tabs (so unsaved edits count)
//! and cached under a fingerprint, so an unchanged project costs nothing.

use super::*;
use formust_rust::paths::is_target_folder;
use formust_rust::{FORM_SUFFIX, Header};
use std::collections::hash_map::DefaultHasher;
use std::hash::{Hash, Hasher};
use std::io::Read;
use std::sync::atomic::AtomicUsize;
use std::time::Duration;

/// Entries (files and folders) in the tree.
pub const MAX_TREE_ENTRIES: usize = 150;
/// Characters in the tree.
pub const MAX_TREE_CHARS: usize = 4_000;
/// Source summary lines and their characters.
pub const MAX_SUMMARIES: usize = 60;
pub const MAX_SUMMARY_CHARS: usize = 5_000;
/// One summary line.
pub const MAX_LINE_CHARS: usize = 220;
/// More entries than this in one folder are cut with a "... N more" line.
const MAX_PER_DIR: usize = 25;
/// The walk stops after this many files, and at this depth.
const MAX_FILES: usize = 2_000;
const MAX_DEPTH: usize = 8;
/// Rust files bigger than this are listed but not scanned.
const MAX_SCAN_BYTES: u64 = 1_000_000;

/// Folders the walk does not enter: build output, dependencies and the like (`.git` and other hidden
/// folders are skipped by name).
const IGNORED_DIRS: &[&str] = &["target", "node_modules", "vendor"];
/// Compiled products, which are not text: rlibs, object files, dynamic libraries and bundles.
const IGNORED_EXTS: &[&str] = &["o", "a", "rlib", "rmeta", "d", "dylib", "so", "dsym", "app"];

// ---- the scanner ----------------------------------------------------------------------

/// Where a Rust file sits in a Cargo package.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Kind {
    /// `src/main.rs`: the binary's crate root.
    Binary,
    /// `src/lib.rs`: the library's crate root.
    Library,
    /// A file Cargo builds as a target of its own: `src/bin`, `examples`, `tests` and `benches`.
    Target,
    /// Any other module.
    Module,
    /// A form file, `name.frm.rs`, generated by Formust: a standalone copy of its source.
    Form,
}

impl Kind {
    fn word(self) -> &'static str {
        match self {
            Kind::Binary => "binary crate root",
            Kind::Library => "library crate root",
            Kind::Target => "cargo target",
            Kind::Module => "module",
            Kind::Form => "form file",
        }
    }
}

#[derive(Clone, PartialEq, Eq, Debug)]
pub struct Summary {
    pub kind: Kind,
    /// `mod name;` declarations (their files are modules of this one).
    pub mods: Vec<String>,
    /// The paths of the `use` items.
    pub uses: Vec<String>,
    /// Top-level items: `fn main`, `struct App`, `impl eframe::App for App`, `mod tests {}`.
    pub items: Vec<String>,
    /// For a form file, the source it copies and the forms it holds, from its header lines.
    pub form: Option<String>,
}

#[derive(PartialEq, Debug)]
enum Tok {
    Word(String),
    Sym(char),
    /// A string, a character or a lifetime: its text does not matter here.
    Other,
}

/// Words, symbols and literals; comments and the insides of strings are skipped.
fn tokens(src: &str) -> Vec<Tok> {
    let c: Vec<char> = src.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    while i < c.len() {
        let ch = c[i];
        if ch == '/' && c.get(i + 1) == Some(&'/') {
            while i < c.len() && c[i] != '\n' {
                i += 1;
            }
        } else if ch == '/' && c.get(i + 1) == Some(&'*') {
            // Block comments nest.
            let mut depth = 0usize;
            while i < c.len() {
                if c[i] == '/' && c.get(i + 1) == Some(&'*') {
                    depth += 1;
                    i += 2;
                } else if c[i] == '*' && c.get(i + 1) == Some(&'/') {
                    depth -= 1;
                    i += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    i += 1;
                }
            }
        } else if ch == 'r' && raw_string_at(&c, i + 1) {
            // A raw string: r"..." or r#"..."#, closed by a quote and the same number of hashes.
            let hashes = c[i + 1..].iter().take_while(|x| **x == '#').count();
            let mut j = i + 2 + hashes;
            while j < c.len() {
                if c[j] == '"'
                    && c[j + 1..].iter().take(hashes).all(|x| *x == '#')
                    && c.len() >= j + 1 + hashes
                {
                    j += 1 + hashes;
                    break;
                }
                j += 1;
            }
            out.push(Tok::Other);
            i = j;
        } else if ch == '"' {
            i += 1;
            while i < c.len() && c[i] != '"' {
                i += if c[i] == '\\' { 2 } else { 1 };
            }
            i += 1;
            out.push(Tok::Other);
        } else if ch == '\'' {
            if c.get(i + 1) == Some(&'\\') {
                // An escaped character: '\n', '\'' and '\u{..}' end at their closing quote.
                i += 2;
                while i < c.len() && c[i] != '\'' {
                    i += 1;
                }
                i += 1;
            } else if c.get(i + 2) == Some(&'\'') {
                i += 3;
            } else {
                // A lifetime: the quote and its name.
                i += 1;
                while i < c.len() && (c[i].is_alphanumeric() || c[i] == '_') {
                    i += 1;
                }
            }
            out.push(Tok::Other);
        } else if ch.is_alphabetic() || ch == '_' {
            let start = i;
            while i < c.len() && (c[i].is_alphanumeric() || c[i] == '_') {
                i += 1;
            }
            out.push(Tok::Word(c[start..i].iter().collect()));
        } else {
            if !ch.is_whitespace() {
                out.push(Tok::Sym(ch));
            }
            i += 1;
        }
    }
    out
}

/// Whether the characters from `i` begin a raw string's hashes and opening quote.
fn raw_string_at(c: &[char], i: usize) -> bool {
    let hashes = c[i.min(c.len())..]
        .iter()
        .take_while(|x| **x == '#')
        .count();
    c.get(i + hashes) == Some(&'"')
}

/// The text of a run of tokens, as written: words are separated by a space, symbols are not.
fn join(toks: &[Tok]) -> String {
    let mut out = String::new();
    let mut last_word = false;
    for t in toks {
        match t {
            Tok::Word(w) => {
                if last_word {
                    out.push(' ');
                }
                out.push_str(w);
                last_word = true;
            }
            Tok::Sym(c) => {
                out.push(*c);
                last_word = false;
            }
            Tok::Other => last_word = false,
        }
    }
    out
}

/// What a Rust source declares at its top level. Items inside a `fn` or an `impl` are not listed.
pub fn scan_rust(src: &str) -> (Vec<String>, Vec<String>, Vec<String>) {
    let toks = tokens(src);
    let (mut mods, mut uses, mut items) = (Vec::new(), Vec::new(), Vec::new());
    let mut depth = 0usize;
    let mut i = 0;
    while i < toks.len() {
        match &toks[i] {
            Tok::Sym('{') => depth += 1,
            Tok::Sym('}') => depth = depth.saturating_sub(1),
            Tok::Word(w) if depth == 0 => match w.as_str() {
                "use" => {
                    let end = toks[i + 1..]
                        .iter()
                        .position(|t| *t == Tok::Sym(';'))
                        .map_or(toks.len(), |k| i + 1 + k);
                    uses.push(join(&toks[i + 1..end]));
                    i = end;
                }
                "mod" => match (toks.get(i + 1), toks.get(i + 2)) {
                    (Some(Tok::Word(name)), Some(Tok::Sym(';'))) => {
                        mods.push(name.clone());
                        i += 2;
                    }
                    (Some(Tok::Word(name)), _) => items.push(format!("mod {name}")),
                    _ => {}
                },
                "impl" => {
                    let end = toks[i + 1..]
                        .iter()
                        .position(|t| matches!(t, Tok::Sym('{') | Tok::Sym(';')))
                        .map_or(toks.len(), |k| i + 1 + k);
                    items.push(format!("impl {}", join(&toks[i + 1..end])));
                    // The `{` (or `;`) is read next, so the body's depth is counted.
                    i = end.saturating_sub(1);
                }
                "fn" | "struct" | "enum" | "trait" | "type" | "const" | "static" | "union" => {
                    if let Some(Tok::Word(name)) = toks.get(i + 1) {
                        items.push(format!("{w} {name}"));
                    }
                }
                _ => {}
            },
            _ => {}
        }
        i += 1;
    }
    (mods, uses, items)
}

/// Where a file sits in its package, from its path (with `/`) alone.
fn kind_of(rel: &str) -> Kind {
    if rel.ends_with(FORM_SUFFIX) {
        return Kind::Form;
    }
    if rel == "src/main.rs" || rel.ends_with("/src/main.rs") {
        Kind::Binary
    } else if rel == "src/lib.rs" || rel.ends_with("/src/lib.rs") {
        Kind::Library
    } else if is_target_folder(Path::new(rel).parent().unwrap_or(Path::new(""))) {
        Kind::Target
    } else {
        Kind::Module
    }
}

/// The summary of a Rust file: its kind, what it declares, and for a form file the source it copies
/// and its forms, from the header lines.
pub fn summarize(rel: &str, src: &str) -> Summary {
    let (mods, uses, items) = scan_rust(src);
    let headers: Vec<Header> = if kind_of(rel) == Kind::Form {
        src.lines().filter_map(Header::parse).collect()
    } else {
        Vec::new()
    };
    let form = headers.first().map(|first| {
        let ids: Vec<&str> = headers.iter().map(|h| h.id.as_str()).collect();
        format!(
            "standalone copy of {} with form {}",
            first.file,
            ids.join(", ")
        )
    });
    Summary {
        kind: kind_of(rel),
        mods,
        uses,
        items,
        form,
    }
}

fn is_rust(rel: &str) -> bool {
    has_ext(rel, &["rs"])
}

fn has_ext(rel: &str, exts: &[&str]) -> bool {
    Path::new(rel)
        .extension()
        .and_then(|e| e.to_str())
        .is_some_and(|e| exts.iter().any(|x| x.eq_ignore_ascii_case(e)))
}

// ---- the disk ---------------------------------------------------------------------------

fn is_macho(path: &Path) -> bool {
    let mut b = [0u8; 4];
    let Ok(mut f) = std::fs::File::open(path) else {
        return false;
    };
    if f.read_exact(&mut b).is_err() {
        return false;
    }
    matches!(
        b,
        [0xcf, 0xfa, 0xed, 0xfe] | [0xce, 0xfa, 0xed, 0xfe] | [0xca, 0xfe, 0xba, 0xbe]
    )
}

fn ignored_dir(name: &str) -> bool {
    name.starts_with('.')
        || IGNORED_DIRS.iter().any(|d| name.eq_ignore_ascii_case(d))
        || has_ext(name, &["app", "dSYM"])
}

fn ignored_file(path: &Path, name: &str) -> bool {
    name.starts_with('.')
        || has_ext(name, IGNORED_EXTS)
        // A compiled program has no extension; a README or Makefile is text.
        || (Path::new(name).extension().is_none() && is_macho(path))
}

/// Project-relative paths (with `/`), sorted; `true` when the walk was cut short.
pub fn walk(root: &Path) -> (Vec<String>, bool) {
    let mut files = Vec::new();
    let mut cut = false;
    let mut stack = vec![(root.to_path_buf(), String::new(), 0usize)];
    while let Some((dir, prefix, depth)) = stack.pop() {
        let Ok(rd) = std::fs::read_dir(&dir) else {
            continue;
        };
        for e in rd.flatten() {
            let name = e.file_name().to_string_lossy().into_owned();
            let Ok(ft) = e.file_type() else { continue };
            let rel = format!("{prefix}{name}");
            if ft.is_dir() {
                if depth + 1 < MAX_DEPTH && !ignored_dir(&name) {
                    stack.push((e.path(), format!("{rel}/"), depth + 1));
                }
            } else if ft.is_file() && !ignored_file(&e.path(), &name) {
                if files.len() >= MAX_FILES {
                    cut = true;
                } else {
                    files.push(rel);
                }
            }
        }
    }
    files.sort_by_key(|f| f.to_lowercase());
    (files, cut)
}

fn read_capped(path: &Path, max: u64) -> Option<String> {
    let f = std::fs::File::open(path).ok()?;
    if f.metadata().ok()?.len() > max {
        return None;
    }
    let mut buf = Vec::new();
    f.take(max).read_to_end(&mut buf).ok()?;
    Some(String::from_utf8_lossy(&buf).into_owned())
}

/// What the disk says about the project.
#[derive(Clone, PartialEq, Eq, Debug, Default)]
pub struct Index {
    pub root: PathBuf,
    pub files: Vec<String>,
    /// Rust files by project-relative path.
    pub sources: HashMap<String, Summary>,
    pub truncated: bool,
}

impl Index {
    pub fn scan(root: &Path) -> Index {
        let (files, truncated) = walk(root);
        let mut idx = Index {
            root: root.to_path_buf(),
            truncated,
            ..Index::default()
        };
        for rel in &files {
            if is_rust(rel)
                && let Some(text) = read_capped(&root.join(rel), MAX_SCAN_BYTES)
            {
                idx.sources.insert(rel.clone(), summarize(rel, &text));
            }
        }
        idx.files = files;
        idx
    }
}

// ---- rendering --------------------------------------------------------------------------

#[derive(Default)]
struct Node {
    dirs: std::collections::BTreeMap<String, Node>,
    files: Vec<String>,
}

fn tree_lines(node: &Node, depth: usize, out: &mut Vec<(String, bool)>) {
    let pad = "  ".repeat(depth);
    let mut shown = 0;
    let total = node.dirs.len() + node.files.len();
    for (name, child) in &node.dirs {
        if shown >= MAX_PER_DIR {
            break;
        }
        shown += 1;
        // A folder that holds only one folder is written as one line: a/b/c/.
        let (mut label, mut cur) = (name.clone(), child);
        while cur.files.is_empty() && cur.dirs.len() == 1 {
            let (n, c) = cur.dirs.iter().next().expect("one folder");
            label = format!("{label}/{n}");
            cur = c;
        }
        out.push((format!("{pad}{label}/"), true));
        tree_lines(cur, depth + 1, out);
    }
    for f in &node.files {
        if shown >= MAX_PER_DIR {
            break;
        }
        shown += 1;
        out.push((format!("{pad}{f}"), true));
    }
    if total > shown {
        out.push((format!("{pad}... {} more here", total - shown), false));
    }
}

/// The file tree as text, within `max_entries` lines and `max_chars` characters. Folders come
/// first, a folder with many entries is cut, and the end says how many entries were left out.
pub fn render_tree(files: &[String], max_entries: usize, max_chars: usize) -> String {
    let mut root = Node::default();
    for f in files {
        let mut parts: Vec<&str> = f.split('/').collect();
        let Some(file) = parts.pop() else { continue };
        let mut n = &mut root;
        for d in parts {
            n = n.dirs.entry(d.to_string()).or_default();
        }
        n.files.push(file.to_string());
    }
    fn sort(n: &mut Node) {
        n.files.sort_by_key(|f| f.to_lowercase());
        n.dirs.values_mut().for_each(sort);
    }
    sort(&mut root);
    let mut lines = Vec::new();
    tree_lines(&root, 0, &mut lines);
    let total = lines.iter().filter(|l| l.1).count();
    let (mut out, mut entries) = (String::new(), 0);
    for (text, is_entry) in &lines {
        if (*is_entry && entries >= max_entries) || out.len() + text.len() + 1 > max_chars {
            break;
        }
        entries += usize::from(*is_entry);
        out.push_str(text);
        out.push('\n');
    }
    if entries < total {
        out.push_str(&format!("... {} more\n", total - entries));
    }
    out
}

fn cap_line(s: String) -> String {
    if s.chars().count() <= MAX_LINE_CHARS {
        return s;
    }
    let mut t: String = s.chars().take(MAX_LINE_CHARS - 3).collect();
    t.push_str("...");
    t
}

fn summary_line(rel: &str, s: &Summary) -> String {
    let head = format!("{rel}: {}", s.kind.word());
    // A form's source is worth more than the end of a long `use` list: it is kept, and the lists
    // are cut with "..." when the line would be too long.
    let tail = s
        .form
        .as_ref()
        .map(|f| format!("; {f}"))
        .unwrap_or_default();
    let mut mid = String::new();
    if !s.mods.is_empty() {
        mid.push_str(&format!("; mod {}", s.mods.join(", ")));
    }
    if !s.uses.is_empty() {
        mid.push_str(&format!("; uses {}", s.uses.join(", ")));
    }
    if !s.items.is_empty() {
        mid.push_str(&format!("; items {}", s.items.join(", ")));
    }
    let budget = MAX_LINE_CHARS.saturating_sub(head.chars().count() + tail.chars().count());
    if mid.chars().count() > budget {
        let keep = budget.saturating_sub(3);
        mid = mid.chars().take(keep).collect::<String>() + "...";
    }
    cap_line(format!("{head}{mid}{tail}"))
}

/// The overview text. `overlay` holds the text of open tabs (project-relative path, text); it
/// replaces what the disk had, and adds files the index does not know yet.
pub fn render(idx: &Index, name: &str, overlay: &[(String, String)]) -> String {
    let mut files = idx.files.clone();
    let mut sources = idx.sources.clone();
    for (rel, text) in overlay {
        if !files.contains(rel) {
            files.push(rel.clone());
        }
        if is_rust(rel) {
            sources.insert(rel.clone(), summarize(rel, text));
        }
    }
    files.sort_by_key(|f| f.to_lowercase());
    let mut out = format!("Project: {name}\nFiles:\n");
    out.push_str(&render_tree(&files, MAX_TREE_ENTRIES, MAX_TREE_CHARS));
    if idx.truncated {
        out.push_str("(the project has more files than this list covers)\n");
    }
    // The crate roots first, then the rest alphabetically.
    let mut list: Vec<(&String, &Summary)> = sources.iter().collect();
    let rank = |k: Kind| match k {
        Kind::Binary => 0,
        Kind::Library => 1,
        _ => 2,
    };
    list.sort_by_key(|(rel, s)| (rank(s.kind), rel.to_lowercase()));
    if !list.is_empty() {
        out.push_str("Rust files:\n");
        let (mut n, mut chars) = (0, 0);
        for (rel, s) in &list {
            let line = summary_line(rel, s);
            if n >= MAX_SUMMARIES || chars + line.len() + 1 > MAX_SUMMARY_CHARS {
                break;
            }
            chars += line.len() + 1;
            n += 1;
            out.push_str(&line);
            out.push('\n');
        }
        if n < list.len() {
            out.push_str(&format!("... {} more\n", list.len() - n));
        }
    }
    out
}

// ---- keeping it fresh -------------------------------------------------------------------

#[derive(Default)]
struct Slot {
    index: Option<Arc<Index>>,
    /// Counts the scans that found something new.
    generation: u64,
    running: bool,
    started: Option<std::time::Instant>,
}

/// The project index (rescanned on a worker thread) and the cached overview text.
#[derive(Default)]
pub struct Project {
    slot: Arc<Mutex<Slot>>,
    cache: Mutex<Option<(u64, String)>>,
    /// How often the text was rendered (tests).
    pub renders: AtomicUsize,
}

impl Project {
    /// Starts a rescan when there is none for `root` yet or the last one is older than
    /// `max_age`. Cheap to call every frame; never blocks.
    pub fn poll(&self, root: &Path, ctx: Option<&egui::Context>, max_age: Duration) {
        {
            let mut s = lock(&self.slot);
            let fresh = s.index.as_ref().is_some_and(|i| i.root == root)
                && s.started.is_some_and(|t| t.elapsed() < max_age);
            if s.running || fresh {
                return;
            }
            s.running = true;
            s.started = Some(std::time::Instant::now());
        }
        let slot = self.slot.clone();
        let root = root.to_path_buf();
        let ctx = ctx.cloned();
        std::thread::spawn(move || {
            let idx = Index::scan(&root);
            let mut s = lock(&slot);
            if s.index.as_deref() != Some(&idx) {
                s.generation += 1;
                s.index = Some(Arc::new(idx));
            }
            s.running = false;
            drop(s);
            if let Some(c) = ctx {
                c.request_repaint();
            }
        });
    }

    /// Replaces the index (tests).
    #[cfg(test)]
    pub fn set_index(&self, idx: Index) {
        let mut s = lock(&self.slot);
        s.generation += 1;
        s.index = Some(Arc::new(idx));
        s.started = Some(std::time::Instant::now());
    }

    /// The overview for `root`, from the cache when neither the index nor an open tab's text
    /// changed. `None` while no scan has finished.
    pub fn text(&self, root: &Path, overlay: &[(String, String)]) -> Option<String> {
        let (idx, generation) = {
            let s = lock(&self.slot);
            (s.index.clone()?, s.generation)
        };
        if idx.root != root {
            return None;
        }
        let mut h = DefaultHasher::new();
        (root, generation).hash(&mut h);
        for (rel, text) in overlay {
            (rel, text.len(), text).hash(&mut h);
        }
        let key = h.finish();
        let mut cache = lock(&self.cache);
        if let Some((k, t)) = cache.as_ref()
            && *k == key
        {
            return Some(t.clone());
        }
        self.renders.fetch_add(1, Ordering::Relaxed);
        let name = root.file_name().map_or_else(
            || "project".to_string(),
            |n| n.to_string_lossy().into_owned(),
        );
        let text = render(&idx, &name, overlay);
        *cache = Some((key, text.clone()));
        Some(text)
    }
}

